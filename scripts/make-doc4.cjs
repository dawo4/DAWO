let imgSeq = 0
function pngSize(file) { const b = fs.readFileSync(file); return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) } }
function img(name, caption, width = 540) {
  const p = path.join(SHOTS, name + '.png')
  if (!fs.existsSync(p)) { console.log('缺图:', name); return null }
  imgSeq++
  const no = String(imgSeq).padStart(2, '0')
  fs.copyFileSync(p, path.join(IMG_OUT, `${no}-${caption.replace(/[\\/:*?"<>|]/g, '')}.png`))
  const { w, h } = pngSize(p)
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 120, after: 80 }, children: [new ImageRun({ type: 'png', data: fs.readFileSync(p), transformation: { width, height: Math.round(width * h / w) } })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 240 }, children: [new TextRun({ text: `图 ${imgSeq}　${caption}（配图 ${no}）`, size: 18, color: '888888' })] })
  ]
}
